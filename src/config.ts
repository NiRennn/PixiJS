export type ItemType =
  | 'tools'
  | 'furniture'
  | 'plants'
  | 'bakery'
  | 'sewing'
  | 'fishing'
  | 'music'
  | 'coins';

export interface ItemData {
  id: string;
  type: ItemType;
  level: number;          // 1..9 для предметов, 1..5 для монет, 0 для генераторов
  isGenerator?: boolean;  // Генератор ли это
  isCobwebbed?: boolean;  // Заблокирован ли паутиной
  generatorTapsLeft?: number; // Остаток тапов до кулдауна (макс 15)
  cooldownUntil?: number;     // Время окончания кулдауна (Date.now() ms)
  lastRechargeTime?: number;  // Время последнего восстановления тапа
}

export interface CellData {
  col: number;
  row: number;
  item: ItemData | null;
}

